# -*- coding: utf-8 -*-
"""
Скрипт для создания исполняемого файла из Python приложения.
Поддерживает новую модульную структуру в src/.
"""

import subprocess
import sys
import os
import json
import shutil
import re
from pathlib import Path


def install_pyinstaller() -> bool:
    """Установка PyInstaller если он не установлен."""
    try:
        import PyInstaller
        print("PyInstaller already installed")
        return True
    except ImportError:
        print("Installing PyInstaller...")
        result = subprocess.run([sys.executable, "-m", "pip", "install", "pyinstaller"],
                                capture_output=True, text=True, encoding='utf-8')
        if result.returncode == 0:
            print("PyInstaller successfully installed")
            return True
        else:
            print("Error installing PyInstaller:")
            print(result.stderr)
            return False


def clean_build_dirs() -> None:
    """Очистка папок сборки."""
    for dir_name in ['build', 'dist', '__pycache__']:
        path = os.path.join(os.path.dirname(__file__), dir_name)
        if os.path.exists(path):
            shutil.rmtree(path, ignore_errors=True)
            print(f"Cleaned: {dir_name}/")

    # Удаляем .spec файлы
    for file in os.listdir('.'):
        if file.endswith('.spec'):
            os.remove(file)
            print(f"Cleaned: {file}")


def write_version_from_changelog() -> str:
    """
    Прочитать последнюю версию из docs_project/CHANGELOG.md
    и записать её в UI/src/_version.py для встраивания в EXE.
    Возвращает строку версии (например "1.28").
    """
    base_dir = os.path.dirname(os.path.abspath(__file__))
    project_root = os.path.dirname(base_dir)  # корень проекта
    changelog_path = os.path.join(project_root, 'docs_project', 'CHANGELOG.md')
    version_py = os.path.join(base_dir, 'src', '_version.py')

    version = "0.0.0-dev"
    if os.path.exists(changelog_path):
        try:
            with open(changelog_path, "r", encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    m = re.match(r'^##\s+v?(\d+(?:\.\d+)+)', line)
                    if m:
                        version = m.group(1)
                        break
        except Exception as e:
            print(f"[WARN] Не удалось прочитать CHANGELOG.md: {e}")

    try:
        with open(version_py, "w", encoding="utf-8") as f:
            f.write(f'# Auto-generated by build_exe.py — не редактировать вручную\n')
            f.write(f'APP_VERSION = "{version}"\n')
        print(f"Версия из CHANGELOG.md записана в _version.py: {version}")
    except Exception as e:
        print(f"[WARN] Не удалось записать _version.py: {e}")

    return version


def _read_env_value(env_path: str, key: str) -> str:
    """Значение ключа из .env-файла. Кавычки и BOM снимаются."""
    if not os.path.exists(env_path):
        return ""
    try:
        with open(env_path, "r", encoding="utf-8-sig") as f:
            for line in f:
                line = line.strip()
                if not line.startswith(f"{key}="):
                    continue
                value = line.split("=", 1)[1].strip()
                if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
                    value = value[1:-1]
                return value
    except OSError:
        pass
    return ""


def read_build_api_token(env_path: str | None = None) -> tuple[str, str]:
    """
    Прочитать API-токен для вшивки в EXE.

    Приоритет: переменная окружения UI_BUILD_API_TOKEN → API_TOKEN →
    строка API_TOKEN= в bot/.env. Возвращает (токен, источник).
    """
    for name in ("UI_BUILD_API_TOKEN", "API_TOKEN"):
        value = os.environ.get(name, "").strip()
        if value:
            return value, f"переменная окружения {name}"
    if env_path is None:
        project_root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
        env_path = os.path.join(project_root, "bot", ".env")
    token = _read_env_value(env_path, "API_TOKEN")
    if token:
        return token, os.path.basename(os.path.dirname(env_path)) + "/.env"
    return "", ""


def write_api_secret(token: str, target: str | None = None) -> str:
    """Создать сгенерированный модуль с токеном — он уедет в бандл EXE."""
    if target is None:
        target = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                              "src", "_api_secret.py")
    with open(target, "w", encoding="utf-8") as f:
        f.write("# Auto-generated by build_exe.py — не редактировать вручную\n")
        f.write(f"API_TOKEN = {json.dumps(token)}\n")
    return target


def remove_api_secret(target: str | None = None) -> None:
    """Удалить сгенерированный модуль — секрет не должен лежать в исходниках."""
    if target is None:
        target = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                              "src", "_api_secret.py")
    try:
        os.remove(target)
    except OSError:
        pass


def create_executable() -> bool:
    """Создание полностью автономного exe файла."""
    if not install_pyinstaller():
        return False

    try:
        # Определяем пути
        base_dir = os.path.dirname(os.path.abspath(__file__))
        project_root = os.path.dirname(base_dir)  # корень проекта (на уровень выше UI/)
        src_dir = os.path.join(base_dir, 'src')
        bot_config_dir = os.path.join(project_root, 'bot', 'config')
        fonts_dir = os.path.join(base_dir, 'assets', 'fonts')
        icon_ico_path = os.path.join(base_dir, 'icon.ico')
        icon_png_path = os.path.join(base_dir, 'icon.png')
        db_viewer = os.path.join(base_dir, 'db_viewer.py')

        # Команда для создания exe
        cmd = [
            sys.executable, '-m', 'PyInstaller',
            '--onefile',              # Один exe файл
            '--windowed',             # Без консоли (GUI приложение)
            '--name=[Search]Driver',  # Имя exe файла
            f'--icon={icon_ico_path}',  # Иконка EXE-файла и окна
            '--noconfirm',            # Не спрашивать подтверждение
            '--clean',                # Очистить перед сборкой
            # Добавляем src, bot/config, шрифты и иконки как data (внутрь single EXE)
            f'--add-data={src_dir}{os.pathsep}src',
            f'--add-data={bot_config_dir}{os.pathsep}bot_config',
            f'--add-data={fonts_dir}{os.pathsep}fonts',
            f'--add-data={icon_ico_path}{os.pathsep}.',
            f'--add-data={icon_png_path}{os.pathsep}.',
            # Пути для поиска пакетов
            f'--paths={project_root}',
            # Скрытые импорты для надежности
            '--hidden-import=tkinter',
            '--hidden-import=PIL',
            '--hidden-import=PIL.Image',
            '--hidden-import=PIL.ImageTk',
            '--hidden-import=PIL._tkinter_finder',
            '--hidden-import=reportlab',
            '--hidden-import=reportlab.pdfgen',
            '--hidden-import=reportlab.lib.pagesizes',
            '--hidden-import=reportlab.pdfbase',
            '--hidden-import=reportlab.pdfbase.ttfonts',
            '--hidden-import=reportlab.lib.utils',
            '--hidden-import=urllib.request',
            '--hidden-import=urllib.parse',
            '--hidden-import=json',
            '--hidden-import=threading',
            '--hidden-import=concurrent.futures',
            '--hidden-import=src',
            '--hidden-import=src.config',
            '--hidden-import=src._api_secret',
            '--hidden-import=src.api_client',
            '--hidden-import=src.models',
            '--hidden-import=src.services',
            '--hidden-import=src.widgets',
            '--hidden-import=src.dialogs',
            '--hidden-import=src.main',
            '--hidden-import=src.logging_config',
            '--hidden-import=fitz',
            '--hidden-import=openpyxl',
            '--hidden-import=et_xmlfile',
            db_viewer
        ]

        print("\n" + "=" * 50)
        print("Creating executable...")
        print("=" * 50)
        print("Command:", ' '.join(cmd))

        result = subprocess.run(cmd, cwd=base_dir, encoding='utf-8', errors='replace')

        if result.returncode == 0:
            exe_path = os.path.join(base_dir, 'dist', '[Search]Driver.exe')
            if os.path.exists(exe_path):
                size_mb = os.path.getsize(exe_path) / 1024 / 1024
                print(f"\nExecutable created successfully!")
                print(f"Path: {exe_path}")
                print(f"Size: {size_mb:.1f} MB")
                print(f"\nFile can run on any Windows computer without Python!")
                return True
            else:
                print("Executable not found after build")
                return False
        else:
            print("Error creating exe file (see PyInstaller output above)")
            return False

    except Exception as e:
        print(f"Error: {e}")
        import traceback
        traceback.print_exc()
        return False


def main():
    print("=" * 50)
    print("Build URIS Consult DB Viewer to EXE")
    print("=" * 50)

    # Записать версию из CHANGELOG.md в код перед сборкой
    app_version = write_version_from_changelog()
    print(f"Сборка версии: {app_version}")

    # Очистка перед сборкой
    clean_build_dirs()

    token, source = read_build_api_token()
    if token:
        print(f"API-токен вшивается в EXE (источник: {source}, значение скрыто)")
    else:
        print("[ВНИМАНИЕ] API-токен не найден — EXE будет без встроенного токена.")
        print("          Задайте UI_BUILD_API_TOKEN или API_TOKEN в окружении,")
        print("          либо строку API_TOKEN= в bot/.env и пересоберите.")

    try:
        write_api_secret(token)
        if create_executable():
            print("\nDone! Application built to exe file.")
            print("File is in 'dist' folder")
        else:
            print("\nError creating exe file.")
            print("Check messages above for diagnostics.")
    finally:
        remove_api_secret()

    input("\nPress Enter to exit...")


if __name__ == "__main__":
    try:
        main()
    except Exception as e:
        print(f"\nFATAL ERROR: {e}")
        import traceback
        traceback.print_exc()
        input("\nPress Enter to exit...")